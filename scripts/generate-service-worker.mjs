import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const outputDirectory = process.env.PWA_OUTPUT_DIRECTORY ?? 'dist';
const workerPath = join(outputDirectory, 'sw.js');

async function filesIn(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesIn(path) : [path];
  }));
  return files.flat();
}

const files = (await filesIn(outputDirectory))
  .filter(path => path !== workerPath)
  .sort((left, right) => left.localeCompare(right));
const inventory = await Promise.all(files.map(async path => {
  const contents = await readFile(path);
  return {
    url: './' + relative(outputDirectory, path).replaceAll('\\', '/'),
    bytes: (await stat(path)).size,
    digest: createHash('sha256').update(contents).digest('hex'),
  };
}));
const version = createHash('sha256')
  .update(inventory.map(asset => `${asset.url}:${asset.bytes}:${asset.digest}`).join('\n'))
  .digest('hex')
  .slice(0, 16);

const worker = `/* Generated by scripts/generate-service-worker.mjs. */
const CACHE_NAME = ${JSON.stringify(`alien-artillery-${version}`)};
const ASSET_URLS = ${JSON.stringify(inventory.map(asset => asset.url))};

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(ASSET_URLS)));
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(
    keys.filter(key => key.startsWith('alien-artillery-') && key !== CACHE_NAME).map(key => caches.delete(key)),
  )).then(() => self.clients.claim()));
});

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(caches.match('./index.html').then(cached => cached ?? fetch(request)));
    return;
  }
  event.respondWith(caches.match(request).then(cached => cached ?? fetch(request)));
});

self.addEventListener('message', event => {
  if (event.data?.type === 'ACTIVATE_UPDATE') self.skipWaiting();
});
`;

await writeFile(workerPath, worker, 'utf8');
